"""Read tools over a committed WorldIR + the tool registry/schemas.

Pure functions: no I/O, no clocks, no RNG. Honesty rule: a fact the world does not record is reported as
"Not recorded" / "Unknown", never invented. Edit tools live in apps/api/routes_assistant.py because they
must go through the one write path; here they are only described in the registry.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Any

from world_ir import measure
from world_ir.world_v1 import WorldIR

NOT_RECORDED = "Not recorded"
EDIT_KINDS = ("room", "corridor", "city", "apartment", "building", "district")
EDIT_OPS = ("update_generated", "delete_generated")
MAX_LIMIT = 500


class ToolError(ValueError):
    """Bad tool name/arguments; the HTTP layer maps this to 422."""


@dataclass
class Context:
    world: WorldIR
    scale_state: str = "unknown"  # metric | authored | unknown


# ------------------------------------------------------------------ helpers

def _pval(x: Any) -> str:
    return getattr(x, "value", None) or str(x)


def provenance_label(e) -> str:
    """OBSERVED/RECONSTRUCTED/GENERATED/PROCEDURAL/...; GENERATED by a stored grammar spec reads as PROCEDURAL."""
    p = _pval(e.provenance)
    if p == "GENERATED" and e.custom_properties.get("generated_by"):
        return "PROCEDURAL"
    return p


def _confidence(e) -> Any:
    """Entity confidence defaults to 0.5 = 'not measured'; uncertainty defaults to 0.0 = unknown."""
    if e.uncertainty is not None and e.uncertainty.confidence > 0:
        return e.uncertainty.confidence
    if e.confidence != 0.5:
        return e.confidence
    return NOT_RECORDED


def _note(e) -> str:
    return e.uncertainty.note if e.uncertainty is not None and e.uncertainty.note else NOT_RECORDED


def _summary(e) -> dict:
    return {"id": e.id, "type": _pval(e.type), "name": e.name or NOT_RECORDED, "provenance": provenance_label(e)}


def _bounds(world: WorldIR, e) -> list:
    out = []
    for gid in e.geometry_ids:
        g = world.geometries.get(gid)
        if g is not None and g.bounds_min is not None and g.bounds_max is not None:
            out.append({"geometry_id": gid,
                        "min": [g.bounds_min.x, g.bounds_min.y, g.bounds_min.z],
                        "max": [g.bounds_max.x, g.bounds_max.y, g.bounds_max.z]})
    return out


def _evidence(e) -> dict:
    obs = [{"id": o.id, "sensor_type": o.sensor_type or NOT_RECORDED, "data_uri": o.data_uri or NOT_RECORDED}
           for o in e.observations]
    refs = [r.to_dict() for r in e.external_references]
    ids = e.custom_properties.get("evidence_ids")
    return {"observations": obs, "external_references": refs,
            "evidence_ids": list(ids) if isinstance(ids, list) else []}


def _require(ctx: Context, eid: str):
    e = ctx.world.entities.get(eid)
    if e is None:
        raise ToolError(f"no entity with id {eid!r}")
    return e


# ---------------------------------------------------------------- read tools

def list_entities(ctx: Context, kind: str | None = None, provenance: str | None = None,
                  limit: int = 100, offset: int = 0) -> dict:
    rows = [e for e in ctx.world.entities.values()
            if (kind is None or _pval(e.type) == kind)
            and (provenance is None or provenance_label(e) == provenance.upper())]
    rows.sort(key=lambda e: e.id)
    return {"total": len(rows), "offset": offset, "limit": limit,
            "entities": [_summary(e) for e in rows[offset:offset + limit]]}


def get_entity(ctx: Context, entity_id: str) -> dict:
    e = _require(ctx, entity_id)
    spec = e.custom_properties.get("spec")
    return {**_summary(e),
            "confidence": _confidence(e),
            "uncertainty_note": _note(e),
            "semantic_labels": list(e.semantic_labels),
            "relationships": [r.to_dict() for r in e.relationships],
            "bounds": _bounds(ctx.world, e),
            "evidence": _evidence(e),
            "spec": spec if isinstance(spec, dict) else None,
            "generated_by": e.custom_properties.get("generated_by"),
            "custom_properties": {k: v for k, v in e.custom_properties.items() if k != "spec"}}


def find_by_name(ctx: Context, name: str) -> dict:
    q = name.strip().lower()
    ents = ctx.world.entities
    exact = sorted(i for i, e in ents.items() if (e.name or "").lower() == q)
    part = sorted(i for i, e in ents.items() if q and q in (e.name or "").lower() and i not in exact)
    return {"query": name, "exact": len(exact), "matches": [_summary(ents[i]) for i in exact + part]}


def measure_tool(ctx: Context, kind: str, points: list, scale_state: str | None = None) -> dict:
    state = scale_state or ctx.scale_state
    try:
        value = measure.compute(kind, measure.validate_points(kind, points))
        unit = measure.unit_for(kind, state)
    except measure.MeasureError as exc:
        raise ToolError(str(exc)) from exc
    return {"kind": kind, "value": value, "unit": unit, "scale_state": state,
            "note": "scale is not known to be metric; value is in model units" if unit.startswith("model") else ""}


def explain_provenance(ctx: Context, entity_id: str) -> dict:
    e = _require(ctx, entity_id)
    label = provenance_label(e)
    ev = _evidence(e)
    cp = e.custom_properties
    if label == "OBSERVED":
        lines = ["Provenance: OBSERVED - directly seen in captured evidence."]
    elif label == "RECONSTRUCTED":
        lines = ["Provenance: RECONSTRUCTED - computed from evidence by the reconstruction pipeline; not seen directly."]
    elif label == "PROCEDURAL":
        spec = cp.get("spec")
        if isinstance(spec, dict):
            lines = [f"Provenance: PROCEDURAL - produced by {spec.get('generator', 'a grammar')} (kind {spec.get('kind')}, "
                     f"seed {spec.get('seed', 0)}) from stored parameters; not real-world evidence."]
        else:
            lines = [f"Provenance: PROCEDURAL - generated as part of {cp['generated_by']!r}, which holds the spec. "
                     "Not real-world evidence."]
    elif label == "GENERATED":
        lines = ["Provenance: GENERATED - proposed content, not observed or reconstructed from evidence."]
        if cp.get("completion_proposal"):
            lines.append(f"Origin: completion proposal {cp['completion_proposal']}.")
    elif label in ("ESTIMATED", "INFERRED"):
        lines = [f"Provenance: {label} - an estimate, not a direct measurement."]
    else:
        lines = ["Provenance: Unknown - the world does not record where this came from."]
    if ev["observations"]:
        lines.append("Observations: " + ", ".join(f"{o['id']} ({o['sensor_type']})" for o in ev["observations"]) + ".")
    if ev["external_references"]:
        lines.append("External references: " + ", ".join(f"{r['kind']}:{r['uri']}" for r in ev["external_references"]) + ".")
    if ev["evidence_ids"]:
        lines.append("Evidence ids: " + ", ".join(map(str, ev["evidence_ids"])) + ".")
    if not (ev["observations"] or ev["external_references"] or ev["evidence_ids"]):
        lines.append(f"Evidence: {NOT_RECORDED}.")
    conf = _confidence(e)
    lines.append(f"Confidence: {conf}.")
    lines.append(f"Uncertainty note: {_note(e)}.")
    return {"entity_id": entity_id, "provenance": label, "evidence": ev, "confidence": conf,
            "text": "\n".join(lines)}


def _tokens(s: str) -> list[str]:
    return "".join(c.lower() if c.isalnum() else " " for c in s).split()


def search(ctx: Context, query: str, limit: int = 20) -> dict:
    qt = _tokens(query)
    if not qt:
        raise ToolError("query has no searchable tokens")
    scored = []
    for e in ctx.world.entities.values():
        props = " ".join(f"{k} {v}" for k, v in e.custom_properties.items()
                         if k != "spec" and isinstance(v, (str, int, float)) and not isinstance(v, bool))
        weighted = [(_tokens(e.name or ""), 3), (_tokens(e.id), 3), (_tokens(_pval(e.type)), 2),
                    (_tokens(" ".join(e.semantic_labels)), 2), (_tokens(provenance_label(e)), 1), (_tokens(props), 1)]
        score = sum(w for toks, w in weighted for t in qt if t in toks)
        if score:
            scored.append((-score, e.id, e))
    scored.sort(key=lambda x: (x[0], x[1]))  # score desc, then id: fully deterministic
    return {"query": query, "total": len(scored),
            "results": [{**_summary(e), "score": -s} for s, _, e in scored[:limit]]}


# ------------------------------------------------------------------ registry

def _obj(props: dict, required: list | None = None) -> dict:
    return {"type": "object", "properties": props, "required": required or [], "additionalProperties": False}


_OPERATION = _obj({
    "op": {"type": "string", "enum": list(EDIT_OPS)},
    "kind": {"type": "string", "enum": list(EDIT_KINDS)},
    "name": {"type": "string"},
    "patch": {"type": "object", "description": "update_generated only: same fields as PUT /{kind}s/{name}"},
    "cascade": {"type": "boolean", "description": "delete_generated only: also delete dependents"},
}, ["op", "kind", "name"])

_LIMIT = {"type": "integer", "minimum": 1, "maximum": MAX_LIMIT}

TOOLS: dict[str, dict] = {
    "list_entities": dict(fn=list_entities, mutating=False,
        description="List entities, optionally filtered by type and provenance (OBSERVED, RECONSTRUCTED, GENERATED, PROCEDURAL, ...).",
        parameters=_obj({"kind": {"type": "string"}, "provenance": {"type": "string"}, "limit": _LIMIT,
                         "offset": {"type": "integer", "minimum": 0}})),
    "get_entity": dict(fn=get_entity, mutating=False,
        description="Full record of one entity: provenance, confidence, evidence, bounds, stored spec.",
        parameters=_obj({"entity_id": {"type": "string"}}, ["entity_id"])),
    "find_by_name": dict(fn=find_by_name, mutating=False,
        description="Find entities by exact or partial name (case-insensitive).",
        parameters=_obj({"name": {"type": "string"}}, ["name"])),
    "measure": dict(fn=measure_tool, mutating=False,
        description="Compute distance/height/area/elevation_difference from points; metres only when scale is metric/authored.",
        parameters=_obj({"kind": {"type": "string", "enum": list(measure.KINDS)}, "points": {"type": "array"},
                         "scale_state": {"type": "string", "enum": list(measure.SCALE_STATES)}}, ["kind", "points"])),
    "explain_provenance": dict(fn=explain_provenance, mutating=False,
        description="Plain-text account of where an entity's facts came from; unrecorded facts are stated as Not recorded/Unknown.",
        parameters=_obj({"entity_id": {"type": "string"}}, ["entity_id"])),
    "search": dict(fn=search, mutating=False,
        description="Deterministic token search over names, ids, types, labels, provenance and simple properties.",
        parameters=_obj({"query": {"type": "string"}, "limit": _LIMIT}, ["query"])),
    "propose_edit": dict(fn=None, mutating=True,
        description="Validate an edit and return a preview plan. Never commits; confirm via POST .../assistant/confirm.",
        parameters=_obj({"operation": _OPERATION}, ["operation"])),
}

_TYPES = {"string": str, "integer": int, "number": (int, float), "boolean": bool, "array": list, "object": dict}


def validate_args(schema: dict, args: Any, path: str = "args") -> None:
    if not isinstance(args, dict):
        raise ToolError(f"{path} must be an object")
    props = schema.get("properties", {})
    for k in schema.get("required", []):
        if k not in args:
            raise ToolError(f"{path}.{k} is required")
    for k, v in args.items():
        if k not in props:
            raise ToolError(f"{path}.{k} is not a known argument")
        spec = props[k]
        t = spec.get("type")
        if t and (not isinstance(v, _TYPES[t]) or (t in ("integer", "number") and isinstance(v, bool))
                  or (t == "number" and not math.isfinite(v))):
            raise ToolError(f"{path}.{k} must be {t}")
        if "enum" in spec and v not in spec["enum"]:
            raise ToolError(f"{path}.{k} must be one of {spec['enum']}")
        if ("minimum" in spec and v < spec["minimum"]) or ("maximum" in spec and v > spec["maximum"]):
            raise ToolError(f"{path}.{k} out of range")
        if t == "object" and "properties" in spec:
            validate_args(spec, v, f"{path}.{k}")


def tool_schemas() -> list[dict]:
    return [{"name": n, "description": t["description"], "mutating": t["mutating"], "parameters": t["parameters"]}
            for n, t in TOOLS.items()]


def call_read_tool(name: str, args: dict, ctx: Context) -> Any:
    t = TOOLS.get(name)
    if t is None:
        raise ToolError(f"unknown tool {name!r}")
    if t["fn"] is None:
        raise ToolError(f"{name!r} is not a read tool")
    validate_args(t["parameters"], args)
    return t["fn"](ctx, **args)
