"""Authoritative catalog of the 50 Open-Source Technologies for Reality Engine evaluation.

Defines the metadata, subsystem classification, open-source licenses, binary/module discovery
targets, hardware-suitability profiles, and evaluation metrics for each of the 50 technologies.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Dict, List, Optional, Tuple


class TechnologySubsystem(str, Enum):
    """Seven specialist subsystems for spatial intelligence."""

    VISUAL_PERCEPTION = "visual_perception"
    GEOMETRIC_ESTIMATION = "geometric_estimation"
    RECONSTRUCTION_MAPPING = "reconstruction_mapping"
    POINTCLOUD_3D_PERCEPTION = "pointcloud_3d_perception"
    GEOMETRY_CAD_MESH = "geometry_cad_mesh"
    GEOSPATIAL_ENVIRONMENT = "geospatial_environment"
    INFERENCE_ACCELERATION = "inference_acceleration"


class HardwareTier(str, Enum):
    """Hardware profile suitability for evaluation environments."""

    CPU_ONLY = "cpu_only"
    LIGHT_GPU = "light_gpu_vram_lt_4gb"
    BALANCED_GPU = "balanced_gpu_4_to_6gb"  # Target for RTX 4050 6GB
    HEAVY_GPU = "heavy_gpu_vram_gt_8gb"


@dataclass(frozen=True)
class TechnologyDescriptor:
    """Immutable specification of one evaluated open-source technology."""

    id: str
    name: str
    subsystem: TechnologySubsystem
    license: str
    repo_url: str
    description: str
    reality_engine_role: str
    binary_names: Tuple[str, ...] = ()
    python_modules: Tuple[str, ...] = ()
    hardware_tier: HardwareTier = HardwareTier.BALANCED_GPU
    evaluation_priority: int = 3  # 1 = top tier, 2 = secondary, 3 = standard
    license_notes: Optional[str] = None
    target_metrics: Tuple[str, ...] = (
        "execution_time_ms",
        "memory_peak_mb",
        "accuracy_or_iou",
        "failure_rate",
    )


