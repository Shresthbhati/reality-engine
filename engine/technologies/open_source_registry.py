"""Loader and validator for the open-source technology registry (engine/technologies/open_source_registry.json).

The JSON is generated by scripts/build_open_source_registry.py from API-verified facts plus curated assessments. This module
only reads it: a technology's classification is data that shows up in a diff, never something code computes or rewrites.
"""
from __future__ import annotations

import json
import pathlib
import re
from typing import Dict, List

REGISTRY_PATH = pathlib.Path(__file__).with_name("open_source_registry.json")

CLASSIFICATIONS = (
    "APPROVED", "APPROVED_WITH_RESTRICTIONS", "RESEARCH_ONLY", "LICENCE_REVIEW_REQUIRED", "REJECTED", "ALREADY_INTEGRATED",
)
REQUIRED_FIELDS = (
    "id", "name", "repository", "commit_sha", "repo_licence", "weights_licence", "classification", "installation", "hardware",
    "capabilities", "integration", "maturity", "benchmark", "fallback", "provenance",
)
#: licence text that cannot sit in a closed commercial product as a linked dependency (LGPL is deliberately not matched)
RESTRICTIVE = re.compile(r"(?<!L)GPL|AGPL|CC BY-NC|cc-by-nc|non-commercial|custom|\bresearch\b")  # lower-case 'research': not 'IDEA-Research'
#: classifications that say "usable in the production path"
USABLE = ("APPROVED", "ALREADY_INTEGRATED")


def load_registry(path: pathlib.Path = REGISTRY_PATH) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def by_id(registry: dict) -> Dict[str, dict]:
    return {r["id"]: r for r in registry["records"]}


def problems(registry: dict, exceptions: Dict[str, str] | None = None) -> List[str]:
    """Every rule violation in ``registry``. ``exceptions`` maps an id to the reason a restrictive licence is still usable
    (e.g. a GPL tool that is only ever run as a separate process); an exception without a reason is not accepted."""
    exceptions = exceptions or {}
    found: List[str] = []
    seen = set()
    for r in registry["records"]:
        rid = r.get("id", "?")
        missing = [f for f in REQUIRED_FIELDS if f not in r]
        if missing:
            found.append(f"{rid}: missing fields {missing}")
            continue
        if rid in seen:
            found.append(f"{rid}: duplicate id")
        seen.add(rid)
        if r["classification"] not in CLASSIFICATIONS:
            found.append(f"{rid}: unknown classification {r['classification']!r}")
        if r["maturity"] not in registry["maturity_ladder"]:
            found.append(f"{rid}: unknown maturity {r['maturity']!r}")
        licences = f"{r['repo_licence']} | {r['weights_licence']}"
        if r["classification"] in USABLE and RESTRICTIVE.search(licences) and not exceptions.get(rid):
            found.append(f"{rid}: classified {r['classification']} but licences read {licences!r}")
        if r["classification"] == "ALREADY_INTEGRATED" and r["integration"].startswith("not integrated"):
            found.append(f"{rid}: ALREADY_INTEGRATED but integration says {r['integration']!r}")
        if r["maturity"] in ("Real-data validated", "Production ready"):
            found.append(f"{rid}: claims {r['maturity']!r}; no real-data benchmark result exists")
    return found
