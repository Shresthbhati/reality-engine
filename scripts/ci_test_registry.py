"""Generate docs/CI_TEST_REGISTRY.md: which test files CI runs, and which it does not."""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CI_YAML = ROOT / ".github/workflows/ci.yml"
OUT = ROOT / "docs/CI_TEST_REGISTRY.md"
_PATH = re.compile(r"tests/[\w./-]+\.py")


def _paths(text: str) -> list[str]:
    return list(dict.fromkeys(_PATH.findall(text)))


def build_registry(ci_yaml: Path, tests_dir: Path) -> dict[str, list[str]]:
    jobs = yaml.safe_load(ci_yaml.read_text(encoding="utf-8"))["jobs"]
    core: list[str] = []
    for step in jobs["core"]["steps"]:
        if step.get("name") == "Run core test suite":
            core = _paths(step["run"])
    fidelity = [p for s in jobs["fidelity-gate"]["steps"] for p in _paths(s.get("run", ""))]
    fidelity = list(dict.fromkeys(fidelity))
    root = tests_dir.parent
    listed = set(core) | set(fidelity)
    unlisted = sorted(
        p for p in (f.relative_to(root).as_posix() for f in tests_dir.rglob("test_*.py"))
        if p not in listed
    )
    return {
        "core": core,
        "fidelity_gate": fidelity,
        "collect_only": ["tests/ (collection only, nothing executed)"],
        "unlisted": unlisted,
        "advisory": ["ruff --exit-zero", "mypy || true"],
    }


def render(registry: dict[str, list[str]]) -> str:
    lines = ["# CI Test Registry", "", "Generated by `scripts/ci_test_registry.py`. Do not edit by hand.", ""]
    for key, items in registry.items():
        lines += [f"## {key}", "", f"Total: {len(items)}", ""]
        lines += [f"- `{i}`" for i in items] + [""]
    return "\n".join(lines)


def main() -> int:
    text = render(build_registry(CI_YAML, ROOT / "tests"))
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else None
        if current != text:
            print(f"{OUT} is out of date; run scripts/ci_test_registry.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
